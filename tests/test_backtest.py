class TestTemporalSplits:
    """Tests for chronological split definitions."""

    def test_training_seasons(self):
        """Training should cover 2015-16 through 2022-23."""
        expected = {"2015-16", "2016-17", "2017-18", "2018-19",
                    "2019-20", "2020-21", "2021-22", "2022-23"}
        assert TRAINING_SEASONS == expected

    def test_validation_seasons(self):
        """Validation should be 2023-24."""
        assert VALIDATION_SEASONS == {"2023-24"}

    def test_test_seasons(self):
        """Test should be 2024-25."""
        assert TEST_SEASONS == {"2024-25"}

    def test_get_split_train(self):
        assert get_split("2022-23") == "train"

    def test_get_split_validation(self):
        assert get_split("2023-24") == "validation"

    def test_get_split_test(self):
        assert get_split("2024-25") == "test"

    def test_splits_are_disjoint(self):
        """No season should appear in more than one split."""
        all_seasons = TRAINING_SEASONS | VALIDATION_SEASONS | TEST_SEASONS
        assert len(all_seasons) == len(TRAINING_SEASONS) + len(VALIDATION_SEASONS) + len(TEST_SEASONS)


